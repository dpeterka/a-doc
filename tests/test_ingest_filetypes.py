def test_detects_a_23andme_style_raw_export_as_genomic(tmp_path: Path) -> None:
    path = tmp_path / "genome_First_Last.txt"
    path.write_text(
        "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2026\n"
        "# Below is a text version of your data.\n"
        "# rsid\tchromosome\tposition\tgenotype\n"
        "rs4477212\t1\t82154\tAA\n"
        "rs3094315\t1\t752566\tAG\n",
        encoding="utf-8",
    )

    assert detect_intake_kind(path) == "genomic"


def test_detects_a_23andme_export_with_an_uncommented_rsid_header(tmp_path: Path) -> None:
    """The header line itself may or may not be commented - both count."""
    path = tmp_path / "genome_First_Last.txt"
    path.write_text(
        "# This data file generated by 23andMe at: Mon Jan 01 00:00:00 2026\n"
        "rsid\tchromosome\tposition\tgenotype\n"
        "rs4477212\t1\t82154\tAA\n",
        encoding="utf-8",
    )

    assert detect_intake_kind(path) == "genomic"


def test_a_txt_file_with_an_rsid_header_but_no_leading_comment_block_is_plain_text(
    tmp_path: Path,
) -> None:
    """The spec is "a leading `# ` comment block FOLLOWED BY" the header -
    a bare rsid table with no comment block first is not sniffed as a
    23andMe export (it just falls through to ordinary "text")."""
    path = tmp_path / "table.txt"
    path.write_text("rsid\tchromosome\tposition\tgenotype\nrs1\t1\t1\tAA\n", encoding="utf-8")

    assert detect_intake_kind(path) == "text"


def test_a_txt_file_with_unrelated_content_after_comments_is_plain_text(tmp_path: Path) -> None:
    path = tmp_path / "notes.txt"
    path.write_text("# just a comment\nsome unrelated narrative text\n", encoding="utf-8")

    assert detect_intake_kind(path) == "text"


def test_detects_a_bgzf_bcf_file_as_genomic(tmp_path: Path) -> None:
    path = tmp_path / "chr1.imputed.bcf"
    path.write_bytes(BGZF_MAGIC + b"\x00" * 32)

    assert detect_intake_kind(path) == "genomic"


def test_detects_a_bgzf_vcf_gz_file_as_genomic(tmp_path: Path) -> None:
    path = tmp_path / "sample.vcf.gz"
    path.write_bytes(BGZF_MAGIC + b"\x00" * 32)

    assert detect_intake_kind(path) == "genomic"


def test_a_gzip_file_with_an_unrelated_suffix_is_not_genomic(tmp_path: Path) -> None:
    path = tmp_path / "archive.tar.gz"
    path.write_bytes(BGZF_MAGIC + b"\x00" * 32)

    assert detect_intake_kind(path) is None


def test_detects_a_plain_vcf_by_its_fileformat_header(tmp_path: Path) -> None:
    path = tmp_path / "sample.vcf"
    path.write_bytes(b"##fileformat=VCFv4.2\n#CHROM\tPOS\tID\n1\t123\trs1\n")

    assert detect_intake_kind(path) == "genomic"


def test_a_vcf_suffixed_file_without_the_real_header_is_not_genomic(tmp_path: Path) -> None:
    path = tmp_path / "sample.vcf"
    path.write_bytes(b"not actually a vcf file at all\n")

    assert detect_intake_kind(path) is None


def test_detects_a_plain_fastq_file_as_genomic(tmp_path: Path) -> None:
    path = tmp_path / "reads.fastq"
    path.write_bytes(b"@SEQ_ID\nGATTACA\n+\n!!!!!!!\n")

    assert detect_intake_kind(path) == "genomic"


