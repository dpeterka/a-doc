"""Tests for adoc.ingest.filetypes.detect_intake_kind - the intake
detection matrix (genomics/filetypes task item 6): pdf, docx (checked
before zip), text (with the oversized-rejection boundary drawn in
`ingest.archive`, not here), genomic (23andMe txt sniff, BGZF .bcf, plain
.vcf, FASTQ), and zip.
"""

from __future__ import annotations

import zipfile
from pathlib import Path

from conftest import TINY_PDF_BYTES
from docx import Document

from adoc.ingest.filetypes import detect_intake_kind

BGZF_MAGIC = bytes.fromhex("1f8b0804")


def test_detects_pdf_by_magic(tmp_path: Path) -> None:
    path = tmp_path / "doc.pdf"
    path.write_bytes(TINY_PDF_BYTES)
    assert detect_intake_kind(path) == "pdf"


def test_detects_a_real_docx_package(tmp_path: Path) -> None:
    path = tmp_path / "notes.docx"
    document = Document()
    document.add_paragraph("hello")
    document.save(str(path))

    assert detect_intake_kind(path) == "docx"


def test_rejects_a_fake_pk_header_without_a_real_zip(tmp_path: Path) -> None:
    """A file merely renamed to `.docx` with a spoofed zip magic, but not an
    actual zip archive, must never be treated as a real docx package."""
    path = tmp_path / "notes.docx"
    path.write_bytes(b"PK\x03\x04 not a real zip at all")

    assert detect_intake_kind(path) is None


def test_rejects_a_real_zip_without_content_types(tmp_path: Path) -> None:
    """A real zip archive that isn't an OOXML package (no
    `[Content_Types].xml`) must not be misdetected as docx even with the
    `.docx` suffix - and since the suffix isn't `.zip`, it isn't picked up
    by the generic zip branch either."""
    path = tmp_path / "notes.docx"
    with zipfile.ZipFile(path, "w") as archive:
        archive.writestr("readme.txt", "just a plain zip")

    assert detect_intake_kind(path) is None


def test_docx_content_saved_with_zip_suffix_is_a_generic_zip_not_docx(tmp_path: Path) -> None:
    """docx detection is gated on BOTH the `.docx` suffix AND the
    `[Content_Types].xml` manifest (checked before the zip branch, per the
    module docstring) - a real OOXML package saved with a `.zip` suffix is
    correctly a generic zip archive to expand, not a docx (and not
    rejected either, now that zip archives are a supported intake kind)."""
    path = tmp_path / "notes.zip"
    document = Document()
    document.add_paragraph("hello")
    document.save(str(path))

    assert detect_intake_kind(path) == "zip"


def test_rejects_unrelated_file_types(tmp_path: Path) -> None:
    path = tmp_path / "notes.png"
    path.write_bytes(b"\x89PNG\r\n\x1a\nnot really a png")

    assert detect_intake_kind(path) is None


def test_rejects_a_missing_file_without_raising(tmp_path: Path) -> None:
    assert detect_intake_kind(tmp_path / "missing.pdf") is None


